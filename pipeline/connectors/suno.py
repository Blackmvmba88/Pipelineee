    @staticmethod
    def parse_track_data(data: dict) -> Track:
        """
        Parse Suno API track data into a Track object.
        
        Args:
            data: Raw track data from Suno API
            
        Returns:
            Track object
        """
        return Track(
            title=data.get("title", ""),
            artist=data.get("artist", data.get("created_by", "")),
            platform=Platform.SUNO,
            platform_id=data.get("id", ""),
            duration_ms=int(data.get("duration", 0) * 1000),  # Suno may use seconds
            album=data.get("album"),
            status=TrackStatus.COMPLETE if data.get("id") else TrackStatus.INCOMPLETE,
            metadata={
                "prompt": data.get("prompt"),
                "style": data.get("style"),
                "audio_url": data.get("audio_url"),
                "created_at": data.get("created_at"),
                "is_public": data.get("is_public"),
            }
        )
